import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const dir=process.argv[2];assert(dir);
const config=JSON.parse(await readFile(`${dir}/episode.json`,'utf8'));
const state=JSON.parse(await readFile(`${dir}/state.json`,'utf8'));
const mp4=`${dir}/${config.fileStem}-full.mp4`;
const probe=JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json',mp4],{encoding:'utf8'}));
const v=probe.streams.find(s=>s.codec_type==='video'),seconds=Number(probe.format.duration);
const target=config.targetSeconds||[45,60],tolerance=config.targetSeconds||[40,65];
assert.equal(v.width,1080);assert.equal(v.height,1920);assert(seconds>=tolerance[0]&&seconds<=tolerance[1],'Voice timing outside short-form editorial tolerance');assert(Math.abs(seconds-state.seconds)<.2);
assert.equal(Object.keys(state.jobs).length,1);assert.equal(state.batches.length,1);
assert.equal(state.batches[0].text,config.sections[0].text);
const source=JSON.parse(await readFile(`${dir}/narration-sources.json`,'utf8'))[0];
assert.equal(source.narration,state.batches[0].text);
const normalize=t=>t.normalize('NFC').replace(/[\p{P}\p{S}\u200c\u200d]/gu,'').trim();
assert.deepEqual(source.captions.flatMap(c=>c.words||[]).map(w=>normalize(w.text)),source.narration.trim().split(/\s+/u).map(normalize));
execFileSync('ffmpeg',['-v','error','-i',mp4,'-f','null','-'],{stdio:'pipe'});
const result={seconds,width:v.width,height:v.height,decodedEntireFile:true,oneApprovedNarrationCall:true,uploadHold:true,target45to60:seconds>=45&&seconds<=60,targetSeconds:target,targetTimingPassed:seconds>=target[0]&&seconds<=target[1]};
await writeFile(`${dir}/verification-full.json`,JSON.stringify(result,null,2));console.log(JSON.stringify(result));
