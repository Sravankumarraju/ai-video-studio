import {readFile,writeFile,copyFile,stat} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {execFileSync} from 'node:child_process';
const dir=process.argv[2];assert(dir);
const config=JSON.parse(await readFile(`${dir}/episode.json`,'utf8'));
const state=JSON.parse(await readFile(`${dir}/state.json`,'utf8'));
const verified=JSON.parse(await readFile(`${dir}/verification-full.json`,'utf8'));
const browser=JSON.parse(await readFile(`${dir}/browser-full-verification.json`,'utf8'));
const review=JSON.parse(await readFile(`${dir}/review-frames.json`,'utf8'));
assert(verified.decodedEntireFile&&verified.targetTimingPassed&&review.reviewed);
assert.equal(browser.renderJobId,state.renderJobs.full);assert(browser.samples.length===3&&browser.samples.every(s=>!s.error&&!s.paused&&s.currentTime>s.requested));
assert((await stat(`${dir}/${config.fileStem}-full.mp4`)).size>1000000);
const delivery={id:config.prefix,title:config.videoTitle,reference:config.reference,projectId:state.projectId,renderJobId:state.renderJobs.full,seconds:verified.seconds,voiceCalls:1,characters:config.sections[0].text.length,mp4:resolve(`${dir}/${config.fileStem}-full.mp4`),fullFileDecoded:true,portrait1080p:true,browserStartMiddleEnd:true,framesReviewed:true,youtubeUploaded:false,uploadHold:true,completedAt:new Date().toISOString()};
await copyFile(`${dir}/hero.png`,`${dir}/thumbnail.png`);
await writeFile(`${dir}/FINAL_DELIVERY.json`,JSON.stringify(delivery,null,2));
await writeFile(`${dir}/README.md`,`${config.videoTitle}\n\nReference ${config.reference}. ${verified.seconds.toFixed(1)} seconds, 1080×1920 portrait. Original Telugu commentary and modern example; full lesson invitation. Fully decoded, reviewed frames, actual browser start/middle/end playback passed.\n\nMedia: ${delivery.mp4}\n\nAll uploads remain held.\n`);
execFileSync('python',['scripts/package-question-short.py',dir],{stdio:'pipe'});
console.log(JSON.stringify(delivery));
